#!/usr/bin/env python3
"""renovate-preset.py [--check] [--root <dir>]: generate the frame rules of the shared Renovate preset (default.json).

The preset lets Renovate update everything a consumer owns and nothing Platform governs (ADR-0037). The frame rules
are the `packageRules` whose description starts with "Frame:"; each one sets `enabled: false` for:
- the Gradle wrapper (the Gradle version belongs to the frame);
- every library of gradle/catalog/libs.versions.toml and every `pl.seniordeveloper:*` artifact;
- every plugin of the catalog and every `seniordev.*` convention plugin, by plugin id and by marker coordinate;
- every key of frontend/packages/versions/versions.json and every `@seniordeveloper-pl-dominik-sienkiewicz/*` package;
- the references to Platform's reusable workflows (`SeniorDeveloper-pl-Dominik-Sienkiewicz/Platform`).
platform-bump moves all of them. The other rules and keys of default.json are hand-written and kept as they are;
the frame rules take the place of the old ones, or go last when there are none.

Without --check the script rewrites default.json. With --check it writes nothing and exits 1 when default.json
differs from what it would write. Platform's CI runs the check through templates/tests/renovate.test.sh.
"""
import argparse
import json
import os
import sys
import tomllib

MARK = "Frame:"
PLATFORM_ARTIFACTS = "pl.seniordeveloper:*"
PLATFORM_PLUGINS = "seniordev.*"
PLATFORM_PACKAGES = ("@seniordeveloper-pl-dominik-sienkiewicz/*", "@dominiksienkiewicz/*")
WIDTH = 120


def library_coordinate(entry):
    if isinstance(entry, str):
        return ":".join(entry.split(":")[:2])
    return entry.get("module") or f"{entry['group']}:{entry['name']}"


def plugin_id(entry):
    return entry.split(":")[0] if isinstance(entry, str) else entry["id"]


def frame_rules(root):
    with open(os.path.join(root, "gradle/catalog/libs.versions.toml"), "rb") as handle:
        catalog = tomllib.load(handle)
    with open(os.path.join(root, "frontend/packages/versions/versions.json"), encoding="utf-8") as handle:
        canon = json.load(handle)["versions"]

    libraries = sorted({
        coordinate for coordinate in map(library_coordinate, catalog.get("libraries", {}).values())
        if not coordinate.startswith(PLATFORM_ARTIFACTS[:-1])
    })
    plugins = sorted({
        plugin for plugin in map(plugin_id, catalog.get("plugins", {}).values())
        if not plugin.startswith(PLATFORM_PLUGINS[:-1])
    })
    plugin_names = [name for plugin in plugins for name in (plugin, f"{plugin}:{plugin}.gradle.plugin")]
    platform_scopes = tuple(pattern[:-1] for pattern in PLATFORM_PACKAGES)
    registry_names = {spec[4:].rsplit("@", 1)[0] for spec in canon.values() if spec.startswith("npm:")}
    packages = sorted(name for name in set(canon) | registry_names if not name.startswith(platform_scopes))

    return [
        {
            "description": f"{MARK} the Gradle version comes from Platform; platform-bump moves the wrapper.",
            "matchManagers": ["gradle-wrapper"],
            "enabled": False,
        },
        {
            "description": f"{MARK} the libraries and BOMs of the Platform catalog and Platform's own artifacts "
                           "(generated from gradle/catalog/libs.versions.toml by scripts/renovate-preset.py); "
                           "platform-bump moves them.",
            "matchManagers": ["gradle"],
            "matchPackageNames": libraries + [PLATFORM_ARTIFACTS],
            "enabled": False,
        },
        {
            "description": f"{MARK} the Gradle plugins of the Platform catalog and Platform's convention plugins, by "
                           "plugin id and by marker coordinate (generated by scripts/renovate-preset.py); "
                           "platform-bump moves them.",
            "matchManagers": ["gradle"],
            "matchPackageNames": plugin_names + [PLATFORM_PLUGINS],
            "enabled": False,
        },
        {
            "description": f"{MARK} the frontend canon and Platform's npm packages (generated from "
                           "frontend/packages/versions/versions.json by scripts/renovate-preset.py); platform-bump "
                           "moves them.",
            "matchManagers": ["npm"],
            "matchPackageNames": [*packages, *PLATFORM_PACKAGES],
            "enabled": False,
        },
        {
            "description": f"{MARK} Platform's reusable workflows are called by an exact vX.Y.Z that platform-bump "
                           "moves; Renovate neither updates nor SHA-pins them.",
            "matchManagers": ["github-actions"],
            "matchDepNames": ["SeniorDeveloper-pl-Dominik-Sienkiewicz/Platform", "DominikSienkiewicz/Platform"],
            "enabled": False,
        },
    ]


def with_frame(preset, rules):
    existing = preset.get("packageRules", [])
    is_frame = [str(rule.get("description", "")).startswith(MARK) for rule in existing]
    at = is_frame.index(True) if any(is_frame) else len(existing)
    kept = [rule for rule, frame in zip(existing, is_frame) if not frame]
    position = sum(1 for frame in is_frame[:at] if not frame)
    return {**preset, "packageRules": kept[:position] + rules + kept[position:]}


def render(value, indent=0):
    """JSON with two-space indentation; a list of at most three scalars that fits the width stays on one line."""
    pad, inner = " " * indent, " " * (indent + 2)
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = [f"{inner}{json.dumps(key, ensure_ascii=False)}: {render(item, indent + 2)}" for key, item in value.items()]
        return "{\n" + ",\n".join(items) + "\n" + pad + "}"
    if isinstance(value, list):
        scalars = all(not isinstance(item, (dict, list)) for item in value)
        inline = "[" + ", ".join(json.dumps(item, ensure_ascii=False) for item in value) + "]"
        if scalars and len(value) <= 3 and indent + len(inline) <= WIDTH:
            return inline
        return "[\n" + ",\n".join(inner + render(item, indent + 2) for item in value) + "\n" + pad + "]"
    return json.dumps(value, ensure_ascii=False)


def main():
    parser = argparse.ArgumentParser(prog="renovate-preset.py", description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when default.json is stale; write nothing")
    parser.add_argument("--root", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    args = parser.parse_args()

    path = os.path.join(args.root, "default.json")
    with open(path, encoding="utf-8") as handle:
        current = handle.read()
    wanted = render(with_frame(json.loads(current), frame_rules(args.root))) + "\n"

    if args.check:
        if current != wanted:
            print("default.json: the frame rules are stale; regenerate them with python3 scripts/renovate-preset.py",
                  file=sys.stderr)
            sys.exit(1)
        print("default.json: the frame rules match the catalog and the frontend canon")
        return
    if current != wanted:
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(wanted)
        print("Regenerated: default.json")


main()
